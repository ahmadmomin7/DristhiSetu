    function b64 = imgToBase64(imgMatrix)
        tempF = [tempname, '.png']; imwrite(imgMatrix, tempF);
        fid = fopen(tempF, 'rb'); rawBytes = fread(fid, inf, 'uint8=>uint8'); fclose(fid); delete(tempF);
        b64 = string(matlab.net.base64encode(rawBytes));
    end
    
    function formatted = formatGeminiResponse(rawText)
        formatted = regexprep(string(rawText), '\*\*(.*?)\*\*', '<b>$1</b>');
        formatted = regexprep(formatted, '(\r\n|\n|\r)', '<br/>');
    end

