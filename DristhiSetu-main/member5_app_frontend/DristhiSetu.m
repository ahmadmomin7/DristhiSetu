            '    <div style="margin-top:16px; display:flex; justify-content:flex-end;">' ...
            '      <button class="btn-pdf-export" onclick="window.triggerPdfExport()">📥 Download Clinical Report (PDF)</button>' ...
            '    </div>' ...
            '  </div>' ...
            '</div>' ...
        ]);
        
        feedHTML.Data = struct('newHtml', string(userSnippet) + string(aiSnippet), 'timestamp', posixtime(datetime('now')));
        capsuleHTML.Data = struct('event', 'reset_attachment');
    end

