    % =========================================================================
    % 2. EVENT CONTROLLERS
    % =========================================================================
    function handleFeedEvents(data)
        if isempty(data) || ~isfield(data, 'action'), return; end
        if strcmp(data.action, 'download_pdf') && ~isempty(lastReportPayload)
            try
                pdfFile = generate_clinical_pdf(lastReportPayload);
                uialert(fig, sprintf('PDF Report successfully generated:\n%s', pdfFile), ...
                        'Report Export Complete', 'Icon', 'success');
            catch ME
                uialert(fig, sprintf('PDF Export error: %s', ME.message), ...
                        'Export Failed', 'Icon', 'error');
            end
        end
    end

    function handleAction(data)
        if isempty(data) || ~isfield(data, 'action'), return; end
        switch data.action
            case 'attach'
                selectScan();
            case 'clear_attachment'
                state.raw = []; state.imgPath = ""; state.imgName = "";
            case 'send'
                processPipeline(string(data.text));
        end
    end

    function selectScan()
        [fName, fPath] = uigetfile({'*.jpg;*.jpeg;*.png;*.tif;*.bmp', 'Retinal Scans'}, 'Select Retinal Fundus Scan');
        if isequal(fName, 0), return; end
        
        state.imgPath = string(fullfile(fPath, fName));
        state.imgName = string(fName);
        raw = imread(fullfile(fPath, fName));
        if ndims(raw) == 2, raw = repmat(raw, 1, 1, 3); elseif size(raw, 3) > 3, raw = raw(:,:,1:3); end
        state.raw = imresize(raw, [584 565]);
        
        thumb = imresize(state.raw, [48 48]);
        capsuleHTML.Data = struct('event', 'image_attached', ...
                                  'b64', "data:image/png;base64," + imgToBase64(thumb), ...
                                  'filename', string(fName));
    end

    function processPipeline(q)
        q = strtrim(q);
        hasImage = ~isempty(state.raw);
        if q == "" && ~hasImage, return; end
        if q == "" && hasImage, q = "Analyze this scan and classify diabetic retinopathy grade."; end
        
        activateChat();
        if hasImage
            userSnippet = sprintf('<div class="msg-user">📎 <b>%s</b><br/>%s</div>', state.imgName, q);
        else
            userSnippet = sprintf('<div class="msg-user">%s</div>', q);
        end
        
        if ~hasImage
            reply = formatGeminiResponse(queryGeminiAgent(q));
            feedHTML.Data = struct('newHtml', string(userSnippet) + sprintf('<div class="msg-ai"><div class="sparkle-icon">✦</div><div>%s</div></div>', reply), 'timestamp', posixtime(datetime('now')));
            return;
        end
        
        % 1. Call Member3 Enhanced_Image.m
        state.clean = Enhanced_Image(state.raw);
        
        % 2. Call Member3 Access_Quality_Local.m
        [passed, sharpVal, contVal] = Access_Quality_Local(state.clean, 22.0, 0.35);
        
        if ~passed
            aiSnippet = string([ ...
                '<div class="msg-ai"><div class="sparkle-icon">✦</div><div class="report-card" style="border-color: rgba(239,68,68,0.5);">' ...
                '<span class="badge badge-danger">Quality Rejected</span>' ...
                '<p style="margin-top:8px; font-size:13px; color:#cbd5e1;">Scan sharpness (<b>' num2str(sharpVal, '%.1f') '</b>) or contrast (<b>' num2str(contVal, '%.2f') '</b>) is below clinical thresholds. Please recapture.</p>' ...
                '</div></div>']);
            feedHTML.Data = struct('newHtml', string(userSnippet) + string(aiSnippet), 'timestamp', posixtime(datetime('now')));
            return;
        end
        
        % 3. Call Member3 extract_biomarkers.m
        [masks, overlayResult, cvMetrics] = extract_biomarkers(state.clean);
        
        % 4. Call Member4 predict_resnet18.m
        [cnnClass, cnnConf, cnnOk] = predict_resnet18(dlNet, state.clean, classNames);
        
        % 5. Hybrid Clinical Decision Gate
        if cvMetrics.neovascular_risk
            gradeStr = "Level 4 – Proliferative DR (PDR)"; refTag = "EMERGENCY (Immediate)"; badgeClass = "badge-danger";
        elseif cvMetrics.foveal_threat || cvMetrics.hemorrhages_count > 10 || cvMetrics.exudates_count > 15
            gradeStr = "Level 3 – Severe NPDR"; refTag = "YES (Urgent)"; badgeClass = "badge-danger";
        elseif cnnOk
            switch cnnClass
                case "Grade_0", gradeStr = "Level 0 – No Diabetic Retinopathy"; refTag = "NO"; badgeClass = "badge-success";
                case "Grade_1", gradeStr = "Level 1 – Mild NPDR"; refTag = "NO (Annual Monitoring)"; badgeClass = "badge-info";
                case "Grade_2", gradeStr = "Level 2 – Moderate NPDR"; refTag = "YES"; badgeClass = "badge-alert";
                case "Grade_3", gradeStr = "Level 3 – Severe NPDR"; refTag = "YES (Urgent)"; badgeClass = "badge-danger";
                case "Grade_4", gradeStr = "Level 4 – Proliferative DR (PDR)"; refTag = "EMERGENCY (Immediate)"; badgeClass = "badge-danger";
                otherwise,      gradeStr = string(cnnClass); refTag = "REFERRAL REQUIRED"; badgeClass = "badge-alert";
            end
        else
            gradeStr = "Level 2 – Moderate NPDR"; refTag = "YES"; badgeClass = "badge-alert";
        end
        
        % 6. Render Colored Visual Strips
        % NEW (Clear, High-Contrast Clinical Masks)
        grayClean = rgb2gray(state.clean);
        bgClear = repmat(imadjust(grayClean, stretchlim(grayClean), [0.15 0.70]), 1, 1, 3);
        
        % Dilate punctate micro-lesions slightly so they pop out clearly on A4 print
        maskEx_plot  = imdilate(masks.exudates, strel('disk', 1));
        maskMA_plot  = imdilate(masks.ma, strel('disk', 2));
        maskHem_plot = imdilate(masks.hem, strel('disk', 1));
        maskFov_plot = imdilate(bwperim(masks.fovea), strel('disk', 2));
        
        imgEx  = Colorize_Image(bgClear, maskEx_plot,  [255, 220, 0]);   % Vivid Yellow
        imgMA  = Colorize_Image(bgClear, maskMA_plot,  [255, 30, 30]);    % Vivid Red
        imgHem = Colorize_Image(bgClear, maskHem_plot, [240, 0, 140]);   % Vivid Magenta
        imgFov = Colorize_Image(bgClear, maskFov_plot, [0, 150, 255]);   % Vivid Blue
        
        b64_raw = imgToBase64(state.raw);
        b64_seg = imgToBase64(overlayResult);
        b64_ex  = imgToBase64(imgEx);
        b64_ma  = imgToBase64(imgMA);
        b64_hem = imgToBase64(imgHem);
        b64_fov = imgToBase64(imgFov);
        
        % 7. Gemini Synchronization
        foveaStr = "No"; if cvMetrics.foveal_threat, foveaStr = "YES (High Risk)"; end
        lQuery = sprintf(['Biomarkers: %d exudates, %d microaneurysms, %d hemorrhages. ' ...
                          'Foveal threat: %s. Neovascular: %s. Prompt: %s'], ...
                          cvMetrics.exudates_count, cvMetrics.microaneurysms_count, cvMetrics.hemorrhages_count, ...
                          foveaStr, string(cvMetrics.neovascular_risk), q);
                      
        if state.imgPath ~= "" && exist(state.imgPath, 'file') == 2
            suggestionsRaw = queryGeminiAgent(gradeStr, lQuery, char(state.imgPath));
        else
            suggestionsRaw = queryGeminiAgent(gradeStr, lQuery);
        end
        suggestionsHtml = formatGeminiResponse(suggestionsRaw);
        
        % Cache payload for PDF generation
        lastReportPayload = struct( ...
            'imgName', state.imgName, ...
            'gradeStr', gradeStr, ...
            'refTag', refTag, ...
            'cnnConf', cnnConf, ...
            'sharpVal', sharpVal, ...
            'contVal', contVal, ...
            'numEx', cvMetrics.exudates_count, ...
            'numMA', cvMetrics.microaneurysms_count, ...
            'numHem', cvMetrics.hemorrhages_count, ...
            'foveaStr', foveaStr, ...
            'isNeovasc', cvMetrics.neovascular_risk, ...
            'rawImg', state.raw, ...
            'overlayImg', overlayResult, ...
            'imgEx', imgEx, ...
            'imgMA', imgMA, ...
            'imgHem', imgHem, ...
            'imgFov', imgFov, ...
            'guidanceHtml', suggestionsHtml ...
        );
        
        % 8. Render UI Assessment Card with Download Action Button
        aiSnippet = string([ ...
            '<div class="msg-ai">' ...
            '  <div class="sparkle-icon">✦</div>' ...
            '  <div class="report-card">' ...
            '    <div style="display:flex; justify-content:space-between; align-items:center; border-bottom:1px solid rgba(255,255,255,0.08); padding-bottom:10px;">' ...
            '      <div><span style="font-size:16px; font-weight:700; color:#f8fafc;">Retinal Diagnostic Assessment</span></div>' ...
            '      <div style="display:flex; gap:8px;">' ...
            '        <span class="badge badge-success">Quality: Passed</span>' ...
            '        <span class="badge ' char(badgeClass) '">' char(gradeStr) '</span>' ...
            '        <span class="badge ' char(badgeClass) '">Referral: ' char(refTag) '</span>' ...
            '      </div>' ...
            '    </div>' ...
            '    <div style="font-size:12.5px; color:#94a3b8; margin:8px 0 12px 0;">ResNet-18 Confidence: <b style="color:#38bdf8;">' num2str(cnnConf, '%.1f') '%</b> | Sharpness: <b>' num2str(sharpVal, '%.1f') '</b> | Contrast: <b>' num2str(contVal, '%.2f') '</b></div>' ...
            '    <div class="grid-images">' ...
            '      <div class="img-wrapper"><div class="img-label">1. Original Input Fundus</div><img class="scan-img" src="data:image/png;base64,' char(b64_raw) '"/></div>' ...
            '      <div class="img-wrapper"><div class="img-label">2. Multi-Biomarker Overlay</div><img class="scan-img" src="data:image/png;base64,' char(b64_seg) '"/></div>' ...
            '    </div>' ...
            '    <div class="grid-biomarkers">' ...
            '      <div class="bio-wrapper"><div class="bio-label" style="color:#fbbf24;">Exudates (' num2str(cvMetrics.exudates_count) ')</div><img class="bio-img" src="data:image/png;base64,' char(b64_ex) '"/></div>' ...
            '      <div class="bio-wrapper"><div class="bio-label" style="color:#f43f5e;">Microaneurysms (' num2str(cvMetrics.microaneurysms_count) ')</div><img class="bio-img" src="data:image/png;base64,' char(b64_ma) '"/></div>' ...
            '      <div class="bio-wrapper"><div class="bio-label" style="color:#e11d48;">Hemorrhages (' num2str(cvMetrics.hemorrhages_count) ')</div><img class="bio-img" src="data:image/png;base64,' char(b64_hem) '"/></div>' ...
            '      <div class="bio-wrapper"><div class="bio-label" style="color:#38bdf8;">Macular Threat (' char(foveaStr) ')</div><img class="bio-img" src="data:image/png;base64,' char(b64_fov) '"/></div>' ...
            '    </div>' ...
            '    <div class="lesion-box">' ...
            '      <div class="lesion-item"><span>Hard Exudates (Lipid/Fluid Leaks)</span><b style="color:#fbbf24;">' num2str(cvMetrics.exudates_count) ' detected</b></div>' ...
            '      <div class="lesion-item"><span>Microaneurysms (Capillary Swellings)</span><b style="color:#f43f5e;">' num2str(cvMetrics.microaneurysms_count) ' detected</b></div>' ...
            '      <div class="lesion-item"><span>Hemorrhages (Internal Bleeding)</span><b style="color:#e11d48;">' num2str(cvMetrics.hemorrhages_count) ' detected</b></div>' ...
            '      <div class="lesion-item"><span>Macular/Foveal Threat</span><b style="color:#38bdf8;">' char(foveaStr) '</b></div>' ...
            '    </div>' ...
            '    <div style="font-size:12px; font-weight:600; color:#94a3b8; text-transform:uppercase; margin-bottom:6px;">Clinical Guidance & Suggestions:</div>' ...
            '    <div class="advice-box">' char(suggestionsHtml) '</div>' ...
            '    ' ...
