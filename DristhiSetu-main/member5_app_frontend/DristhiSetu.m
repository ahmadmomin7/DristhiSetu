function fig = DristhiSetu
    % =========================================================================
    % 0. PATH LINKING & MODEL LOADING
    % =========================================================================
    thisFile = mfilename('fullpath');
    [currentFolder, ~, ~] = fileparts(thisFile);
    projectRoot = fileparts(currentFolder);
    if isempty(projectRoot), projectRoot = pwd; end
    addpath(genpath(projectRoot));
    warning('off', 'MATLAB:ui:figure:Scrollable');
    
    MODEL_PRIMARY_PATH = 'D:\EyeTriage_Prototype (1)\EyeTriage_Prototype\DR_Project\models\Model1_ResNet18\ResNet18_EyePACS.mat';
