    function activateChat()
        if ~state.isChatActive
            state.isChatActive = true;
            lblHero.Visible = 'off'; lblSubHero.Visible = 'off';
            feedHTML.Visible = 'on';
            set(capsuleHTML, 'Position', [130, 10, 740, 135]);
