    targetModelPath = "";
    if isfile(MODEL_PRIMARY_PATH)
        targetModelPath = MODEL_PRIMARY_PATH;
    elseif isfile(MODEL_FALLBACK_PATH)
        targetModelPath = MODEL_FALLBACK_PATH;
    end
    
    dlNet = [];
    classNames = ["Grade_0", "Grade_1", "Grade_2", "Grade_3", "Grade_4"];
    if targetModelPath ~= ""
        try
            loaded = load(targetModelPath);
            if isfield(loaded, 'netEyePACS'), dlNet = loaded.netEyePACS;
            elseif isfield(loaded, 'net'),     dlNet = loaded.net; end
            if isfield(loaded, 'CLASS_NAMES'), classNames = loaded.CLASS_NAMES; end
            fprintf('[DristhiSetu] ResNet-18 model ready: %s\n', targetModelPath);
        catch ME
            warning('[DristhiSetu] Model load failure: %s', ME.message);
        end
    end

    % =========================================================================
    % 1. UI SETUP & APPLICATION STATE
    % =========================================================================
    fig = uifigure('Name', 'DristhiSetu AI - Retinal Diagnostic Copilot', ...
        'Position', [50, 40, 1000, 720], 'Color', [0.08, 0.09, 0.11], ...
        'Scrollable', 'off', 'Visible', 'on');
    
    state = struct('raw', [], 'clean', [], 'diag', "Unscreened", ...
                   'isChatActive', false, 'imgPath', "", 'imgName', "");
               
    % Cache container for active report export
    lastReportPayload = [];
               
    feedHTML = uihtml(fig, 'Position', [40, 140, 920, 545], 'Visible', 'off');
    feedHTML.HTMLSource = getFeedHTML();
    feedHTML.DataChangedFcn = @(s, e) handleFeedEvents(s.Data);
    
    lblHero = uilabel(fig, 'Position', [100, 420, 800, 55], 'Text', 'DristhiSetu AI', ...
